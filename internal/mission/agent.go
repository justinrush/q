package mission

import (
	"context"
	"os"
	"time"
)

// Agent is one coding agent q can run a mission with.
//
// Everything that differs between claude, codex, and whatever comes next is
// reached through this interface, so adding an agent is a new package rather
// than a new branch in each of these files. Implementations live in
// internal/claude and internal/codex; the cmd package builds them from the
// user's configuration and hands them to a [Service].
//
// An implementation runs no processes and touches no state: it is a pure
// function from an [Invocation] to argv and bytes, which is what lets a whole
// launch be asserted in tests without an agent installed.
type Agent interface {
	// Tool reports which agent this is.
	Tool() Tool
	// Bin is the absolute path to the agent's executable.
	Bin() string
	// Args returns the agent's arguments, already shell-quoted for the launch
	// script.
	Args(Invocation) []string
	// Prologue is shell emitted before the script's final exec, for an agent that
	// needs an environment variable exported, a sidecar started, or a preferred
	// invocation tried first. Most agents return "".
	Prologue(Invocation) string
	// Artifacts are the files the agent needs written before it starts.
	Artifacts(Invocation) ([]Artifact, error)
	// HookEvents lists the hook events the agent is configured to report.
	HookEvents() []string
}

// Invocation is everything an agent needs to know to run one mission.
type Invocation struct {
	// MissionID and HookEpoch identify the mission to its hooks.
	MissionID MissionID
	HookEpoch int
	// MissionDir is the agent's working directory.
	MissionDir string
	// MissionDirs are every mission directory currently on disk, including this
	// one. An agent that must be told which directories it may trust in advance
	// needs the whole set, not just its own.
	MissionDirs []string
	// DaemonFile is the path to the daemon handle.
	DaemonFile string
	// SessionID is the agent session to use or resume. For an agent that accepts
	// a preset id this is chosen in advance; otherwise it is only known after the
	// session has started, and so is empty on a first launch.
	SessionID string
	// Resume continues SessionID rather than starting fresh.
	Resume bool
	// PlanMode starts the agent in a plan-then-approve flow, for an agent that
	// supports one. It is true only while the mission is still planning.
	PlanMode bool
	// Model names the model to run on, as the agent's own CLI names it. Empty
	// means emit no model flag, leaving the agent its own default.
	Model string
	// Effort is the reasoning effort level. Empty means emit no effort flag.
	Effort string
	// ImplementModel and ImplementEffort are what the mission will run on once
	// its plan is accepted. They are set only while PlanMode is, and are for an
	// agent that makes that change itself and so has to be told both ends of it
	// at the start.
	ImplementModel  string
	ImplementEffort string
	// DisplayName is shown in the agent's own UI.
	DisplayName string
	// Worktrees are the absolute worktree paths the agent may touch.
	Worktrees []string
	// PathEnv is the PATH to export, so the agent can find its own tooling even
	// when the daemon was started with a minimal environment.
	PathEnv string
	// QBin is the absolute path to the q binary, embedded in hook commands.
	QBin string
}

// Opener is an agent whose first instruction sometimes has to be typed into its
// UI rather than passed on its command line.
//
// It is optional. An agent implements it when something it must be told at the
// start is only reachable as a command in its own interface, which no argument
// can stand in for.
type Opener interface {
	// Opening returns the text to submit once the agent is accepting input, and
	// false when the command line already carries everything.
	Opening(Invocation) (string, bool)
	// Ready reports whether a capture of the agent's pane shows it waiting for
	// input, as opposed to still starting or stopped at a question of its own.
	Ready(pane string) bool
	// Pending reports whether a capture of the agent's pane shows text still
	// sitting in its input, typed but not yet taken.
	Pending(pane, text string) bool
}

// Artifact is a file an agent needs written before it starts.
type Artifact struct {
	// Path names the file. A relative path is resolved inside the mission's
	// artifact directory; an absolute path is written as given, which is how an
	// agent configured from its own home directory is served.
	Path string
	// Data is the file's contents.
	Data []byte
	// Mode is the file's permissions.
	Mode os.FileMode
	// Merge, when set, combines the generated bytes with what is already on disk
	// and reports whether anything needs writing. It exists for a file an agent
	// writes to as well as reads, such as a profile carrying hook approvals that
	// must survive regeneration.
	Merge func(generated, existing []byte) ([]byte, bool)
}

// Activity is what an agent's own runtime says a session is doing.
type Activity string

// The activities an agent runtime can report.
const (
	ActivityUnknown         Activity = ""
	ActivityBusy            Activity = "busy"
	ActivityWaitingApproval Activity = "waiting_approval"
	ActivityWaitingInput    Activity = "waiting_input"
	ActivityIdle            Activity = "idle"
	ActivityFailed          Activity = "failed"
)

// Reading is one observation of a live agent session.
type Reading struct {
	// SessionID is the agent's own identifier for the session observed.
	SessionID string
	// PreviousSessionID permits replacement only after that recorded thread
	// was observed unloaded and a live root thread was found in the mission cwd.
	PreviousSessionID string
	// TranscriptPath is the local rollout path reported by the runtime.
	TranscriptPath string
	HookEpoch      int
	// PlanKnown distinguishes a structured observation from an unavailable
	// plan-history endpoint. Busy status alone cannot dismiss a plan dialog.
	PlanKnown    bool
	PlanPending  bool
	PlanApproved bool
	// PaneID is the tmux pane the session occupies, when the agent knows it.
	// An agent that reports this beats anything q inferred.
	PaneID string
	// ObservedAt is when the source recorded this status. Zero means unavailable.
	ObservedAt time.Time
	// Activity is what the session is doing.
	Activity Activity
	// WaitingFor describes what a waiting session is blocked on.
	WaitingFor string
}

// Runtime reports process truth from an agent's own runtime.
//
// A Runtime is authoritative: q polls it and its readings move a card in either
// direction, because it observes the running process rather than inferring from
// events that may have been missed.
type Runtime interface {
	Read(ctx context.Context, ms Mission) (Reading, bool, error)
	Close() error
}

// Healer reports what an agent's own session registry says.
//
// A Healer is advisory. Its readings only correct a card that a dropped hook
// left wrong, and each rule is deliberately conservative about the direction it
// moves one, because the registry is a best-effort signal and hooks remain q's
// primary source.
type Healer interface {
	Heal(ctx context.Context, missions []Mission) (map[MissionID]Reading, error)
}

// Metering is one measurement of what a mission's agent session has consumed.
type Metering struct {
	// CodexUsage is the host-local checkpoint underlying Usage.
	CodexUsage CodexUsage
	// Usage is the running total for the session.
	Usage Usage
	// Limit is the most recent refusal the session recorded, zero when the agent
	// has never been turned away.
	Limit Limit
}

// Meter reports what an agent session has consumed.
//
// Like [Runtime] and [Healer] it is optional: without one a mission simply
// carries no cost, and every other part of the board behaves as before. An
// implementation reads whatever the agent already writes down — for claude, the
// transcript q is handed the path to on every hook — rather than calling any
// billing API, so metering costs nothing and needs no credentials.
type Meter interface {
	// Tool reports which agent this meters.
	Tool() Tool
	// Meter measures one mission, reporting false when the session has left
	// nothing to measure yet.
	Meter(ms Mission) (Metering, bool, error)
}
